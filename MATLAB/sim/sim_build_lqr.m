function info = sim_build_lqr(P, opts)
% SIM_BUILD_LQR Build and save model/uacs_lqr.slx.
%
% Full-state feedback with integral augmentation, in the deviation coordinates
% control/design_lqr.m designs on, closed through the same allocation the manual
% model uses:
%   x_dev = x_abs - x_op                                  (Sum with a Constant)
%   z     = integral(C_int*x_dev - r)                      (Discrete-Time Integrator)
%   u_dev = u_ff + K*([x_ref; 0] - [x_dev; z])             (Gain on a 5-vector)
%   surf  = u_trim + [dda dde ddr]                         (surfaces are absolute)
%   M_cmd = G_surf*surf,  T_cmd = T_trim + dT
%   allocate -> [da de dr dth_l dth_r] -> plant
%
% The reference comes from sim_lqr_ref_ts as commanded deviations
% [dV_c dtheta_c dphi_c dbeta_c]; the reference state and the feedforward are
% produced by two matrix Gains, which is exact because lqr_reference solves a
% linear system in those commands. sim_lqr_refmap builds the matrices and checks
% them against a direct solve at a non-unit command.
%
% The plant's longitudinal states are [V alpha q theta] and the lateral ones are
% [beta p r phi], so V and alpha come from the air-data block and the rest are
% selected straight out of the state vector.

if nargin < 2
   opts = struct();
end
mdl = 'uacs_lqr';
file = fullfile(sim_root(), 'model', [mdl '.slx']);
sim_new_model(mdl, file);

% ---------------- sources ----------------
sim_add_block(mdl, 'ref_src', 'simulink/Sources/From Workspace', sim_pos(0, 0, 90, 40), ...
   'VariableName', 'sim_lqr_ref_ts', 'Interpolate', 'on', ...
   'OutputAfterFinalValue', 'Holding final value');
sim_add_block(mdl, 'wind_src', 'simulink/Sources/From Workspace', sim_pos(0, 13, 90, 40), ...
   'VariableName', 'sim_wind_ts', 'Interpolate', 'on', ...
   'OutputAfterFinalValue', 'Holding final value');
sim_add_block(mdl, 'const_utrim', 'simulink/Sources/Constant', sim_pos(6, 10, 80, 30), ...
   'Value', 'sim_u_trim_surf');
sim_add_block(mdl, 'const_Ttrim', 'simulink/Sources/Constant', sim_pos(6, 12, 80, 30), ...
   'Value', 'sim_T_trim');
sim_add_block(mdl, 'const_xop_long', 'simulink/Sources/Constant', sim_pos(2, 3, 80, 30), ...
   'Value', 'sim_lqr_xop_long');
sim_add_block(mdl, 'const_xop_lat', 'simulink/Sources/Constant', sim_pos(2, 6, 80, 30), ...
   'Value', 'sim_lqr_xop_lat');
sim_add_block(mdl, 'const_zero', 'simulink/Sources/Constant', sim_pos(6, 0, 60, 30), ...
   'Value', 'sim_c_zero');

% ---------------- reference path ----------------
sim_add_block(mdl, 'ref_split', 'simulink/Signal Routing/Demux', sim_pos(1, 0, 40, 90), ...
   'Outputs', '4');
sim_add_block(mdl, 'ref_long', 'simulink/Signal Routing/Mux', sim_pos(2, 0, 20, 40), ...
   'Inputs', '2');
sim_add_block(mdl, 'Tref_long', 'simulink/Math Operations/Gain', sim_pos(3, 0, 80, 40), ...
   'Gain', 'sim_lqr_Tref_long', 'Multiplication', 'Matrix(K*u)');
sim_add_block(mdl, 'Uff_long', 'simulink/Math Operations/Gain', sim_pos(3, 1, 80, 40), ...
   'Gain', 'sim_lqr_Uff_long', 'Multiplication', 'Matrix(K*u)');
sim_add_block(mdl, 'ref_lat', 'simulink/Signal Routing/Mux', sim_pos(2, 5, 20, 40), ...
   'Inputs', '2');
sim_add_block(mdl, 'Tref_lat', 'simulink/Math Operations/Gain', sim_pos(3, 5, 80, 40), ...
   'Gain', 'sim_lqr_Tref_lat', 'Multiplication', 'Matrix(K*u)');
sim_add_block(mdl, 'Uff_lat', 'simulink/Math Operations/Gain', sim_pos(3, 6, 80, 40), ...
   'Gain', 'sim_lqr_Uff_lat', 'Multiplication', 'Matrix(K*u)');

% ---------------- measurement and state selection ----------------
sim_add_block(mdl, 'meas', 'simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
   sim_pos(1, 2, 100, 40), 'FunctionName', 'sim_meas_sfun');
sim_add_block(mdl, 'meas_split', 'simulink/Signal Routing/Demux', sim_pos(2, 2, 40, 90), ...
   'Outputs', '4');
sim_add_block(mdl, 'x_split', 'simulink/Signal Routing/Demux', sim_pos(1, 8, 40, 260), ...
   'Outputs', '12');

% ---------------- longitudinal loop ----------------
sim_add_block(mdl, 'long_abs', 'simulink/Signal Routing/Mux', sim_pos(3, 2, 20, 90), ...
   'Inputs', '4');
sim_add_block(mdl, 'long_dev', 'simulink/Math Operations/Sum', sim_pos(4, 2, 40, 40), ...
   'Inputs', '+-', 'IconShape', 'rectangular');
sim_add_block(mdl, 'C_long', 'simulink/Math Operations/Gain', sim_pos(5, 2, 60, 30), ...
   'Gain', 'sim_lqr_C_long', 'Multiplication', 'Matrix(K*u)');
sim_add_block(mdl, 'long_int_err', 'simulink/Math Operations/Sum', sim_pos(6, 2, 40, 30), ...
   'Inputs', '+-', 'IconShape', 'rectangular');
sim_add_block(mdl, 'long_int', 'simulink/Discrete/Discrete-Time Integrator', ...
   sim_pos(7, 2, 70, 40), 'gainval', 'sim_c_one', 'SampleTime', 'sim_ts_ctrl', ...
   'LimitOutput', 'on', 'UpperSaturationLimit', 'sim_lqr_zlim_long', ...
   'LowerSaturationLimit', 'sim_lqr_zlim_long_neg');
sim_add_block(mdl, 'long_aug_dev', 'simulink/Signal Routing/Mux', sim_pos(8, 2, 20, 60), ...
   'Inputs', '2');
sim_add_block(mdl, 'long_aug_ref', 'simulink/Signal Routing/Mux', sim_pos(8, 1, 20, 60), ...
   'Inputs', '2');
sim_add_block(mdl, 'long_err', 'simulink/Math Operations/Sum', sim_pos(9, 1, 40, 40), ...
   'Inputs', '+-', 'IconShape', 'rectangular');
sim_add_block(mdl, 'K_long', 'simulink/Math Operations/Gain', sim_pos(10, 1, 80, 40), ...
   'Gain', 'sim_lqr_K_long', 'Multiplication', 'Matrix(K*u)');
sim_add_block(mdl, 'long_uff_sum', 'simulink/Math Operations/Sum', sim_pos(11, 1, 40, 40), ...
   'Inputs', '++', 'IconShape', 'rectangular');
sim_add_block(mdl, 'u_dev_long_split', 'simulink/Signal Routing/Demux', sim_pos(12, 1, 40, 50), ...
   'Outputs', '2');

% ---------------- lateral loop ----------------
sim_add_block(mdl, 'lat_abs', 'simulink/Signal Routing/Mux', sim_pos(3, 5, 20, 90), ...
   'Inputs', '4');
sim_add_block(mdl, 'lat_dev', 'simulink/Math Operations/Sum', sim_pos(4, 5, 40, 40), ...
   'Inputs', '+-', 'IconShape', 'rectangular');
sim_add_block(mdl, 'C_lat', 'simulink/Math Operations/Gain', sim_pos(5, 5, 60, 30), ...
   'Gain', 'sim_lqr_C_lat', 'Multiplication', 'Matrix(K*u)');
sim_add_block(mdl, 'lat_int_err', 'simulink/Math Operations/Sum', sim_pos(6, 5, 40, 30), ...
   'Inputs', '+-', 'IconShape', 'rectangular');
sim_add_block(mdl, 'lat_int', 'simulink/Discrete/Discrete-Time Integrator', ...
   sim_pos(7, 5, 70, 40), 'gainval', 'sim_c_one', 'SampleTime', 'sim_ts_ctrl', ...
   'LimitOutput', 'on', 'UpperSaturationLimit', 'sim_lqr_zlim_lat', ...
   'LowerSaturationLimit', 'sim_lqr_zlim_lat_neg');
sim_add_block(mdl, 'lat_aug_dev', 'simulink/Signal Routing/Mux', sim_pos(8, 5, 20, 60), ...
   'Inputs', '2');
sim_add_block(mdl, 'lat_aug_ref', 'simulink/Signal Routing/Mux', sim_pos(8, 4, 20, 60), ...
   'Inputs', '2');
sim_add_block(mdl, 'lat_err', 'simulink/Math Operations/Sum', sim_pos(9, 4, 40, 40), ...
   'Inputs', '+-', 'IconShape', 'rectangular');
sim_add_block(mdl, 'K_lat', 'simulink/Math Operations/Gain', sim_pos(10, 4, 80, 40), ...
   'Gain', 'sim_lqr_K_lat', 'Multiplication', 'Matrix(K*u)');
sim_add_block(mdl, 'lat_uff_sum', 'simulink/Math Operations/Sum', sim_pos(11, 4, 40, 40), ...
   'Inputs', '++', 'IconShape', 'rectangular');
sim_add_block(mdl, 'u_dev_lat_split', 'simulink/Signal Routing/Demux', sim_pos(12, 4, 40, 50), ...
   'Outputs', '2');

% ---------------- mixing, allocation, plant ----------------
sim_add_block(mdl, 'surf_inc', 'simulink/Signal Routing/Mux', sim_pos(6, 9, 20, 50), ...
   'Inputs', '3');
sim_add_block(mdl, 'surf_sum', 'simulink/Math Operations/Sum', sim_pos(7, 9, 40, 40), ...
   'Inputs', '++', 'IconShape', 'rectangular');
sim_add_block(mdl, 'G_gain', 'simulink/Math Operations/Gain', sim_pos(8, 9, 80, 40), ...
   'Gain', 'sim_G_surf', 'Multiplication', 'Matrix(K*u)');
sim_add_block(mdl, 'T_sum', 'simulink/Math Operations/Sum', sim_pos(7, 12, 40, 30), ...
   'Inputs', '++', 'IconShape', 'rectangular');
sim_add_block(mdl, 'alloc', 'simulink/User-Defined Functions/Level-2 MATLAB S-Function', ...
   sim_pos(8, 10, 110, 60), 'FunctionName', 'sim_alloc_sfun');
sim_add_block(mdl, 'act_split', 'simulink/Signal Routing/Demux', sim_pos(9, 9, 40, 140), ...
   'Outputs', '5');
sim_add_block(mdl, 'u_mux', 'simulink/Signal Routing/Mux', sim_pos(10, 9, 30, 150), ...
   'Inputs', '6');
sim_add_plant_subsystem(mdl, 'plant', sim_pos(11, 9, 150, 150));
sim_add_block(mdl, 'u_dev_mux', 'simulink/Signal Routing/Mux', sim_pos(13, 1, 20, 90), ...
   'Inputs', '4');
sim_add_block(mdl, 'xi_mux', 'simulink/Signal Routing/Mux', sim_pos(13, 5, 20, 50), ...
   'Inputs', '2');

% ---------------- outputs ----------------
sim_add_block(mdl, 'x_state', 'simulink/Sinks/Out1', sim_pos(12, 9, 30, 14), 'Port', '1');
sim_add_block(mdl, 'u_act', 'simulink/Sinks/Out1', sim_pos(12, 10, 30, 14), 'Port', '2');
sim_add_block(mdl, 'M_cmd', 'simulink/Sinks/Out1', sim_pos(12, 11, 30, 14), 'Port', '3');
sim_add_block(mdl, 'T_cmd', 'simulink/Sinks/Out1', sim_pos(12, 12, 30, 14), 'Port', '4');
sim_add_block(mdl, 'u_dev', 'simulink/Sinks/Out1', sim_pos(14, 1, 30, 14), 'Port', '5');
sim_add_block(mdl, 'ref', 'simulink/Sinks/Out1', sim_pos(14, 3, 30, 14), 'Port', '6');
sim_add_block(mdl, 'xi', 'simulink/Sinks/Out1', sim_pos(14, 5, 30, 14), 'Port', '7');

% ---------------- wiring ----------------
sim_connect(mdl, 'ref_src/1', 'ref_split/1', 'ref_src/1', 'ref/1');
sim_connect(mdl, 'ref_split/1', 'ref_long/1', 'ref_split/2', 'ref_long/2', ...
   'ref_long/1', 'Tref_long/1', 'ref_long/1', 'Uff_long/1');
sim_connect(mdl, 'ref_split/4', 'ref_lat/1', 'ref_split/3', 'ref_lat/2', ...
   'ref_lat/1', 'Tref_lat/1', 'ref_lat/1', 'Uff_lat/1');
sim_connect(mdl, 'meas/1', 'meas_split/1', 'meas_split/1', 'long_abs/1', ...
   'meas_split/2', 'long_abs/2', 'meas_split/3', 'lat_abs/1');
sim_connect(mdl, 'x_split/5', 'long_abs/3', 'x_split/8', 'long_abs/4', ...
   'x_split/4', 'lat_abs/2', 'x_split/6', 'lat_abs/3', 'x_split/7', 'lat_abs/4');
sim_connect(mdl, 'long_abs/1', 'long_dev/1', 'const_xop_long/1', 'long_dev/2', ...
   'long_dev/1', 'C_long/1', 'long_dev/1', 'long_aug_dev/1');
sim_connect(mdl, 'C_long/1', 'long_int_err/1', 'ref_split/1', 'long_int_err/2', ...
   'long_int_err/1', 'long_int/1', 'long_int/1', 'long_aug_dev/2');
sim_connect(mdl, 'Tref_long/1', 'long_aug_ref/1', 'const_zero/1', 'long_aug_ref/2', ...
   'long_aug_ref/1', 'long_err/1', 'long_aug_dev/1', 'long_err/2', ...
   'long_err/1', 'K_long/1', 'K_long/1', 'long_uff_sum/2', ...
   'Uff_long/1', 'long_uff_sum/1', 'long_uff_sum/1', 'u_dev_long_split/1');
sim_connect(mdl, 'lat_abs/1', 'lat_dev/1', 'const_xop_lat/1', 'lat_dev/2', ...
   'lat_dev/1', 'C_lat/1', 'lat_dev/1', 'lat_aug_dev/1');
sim_connect(mdl, 'C_lat/1', 'lat_int_err/1', 'ref_split/3', 'lat_int_err/2', ...
   'lat_int_err/1', 'lat_int/1', 'lat_int/1', 'lat_aug_dev/2');
sim_connect(mdl, 'Tref_lat/1', 'lat_aug_ref/1', 'const_zero/1', 'lat_aug_ref/2', ...
   'lat_aug_ref/1', 'lat_err/1', 'lat_aug_dev/1', 'lat_err/2', ...
   'lat_err/1', 'K_lat/1', 'K_lat/1', 'lat_uff_sum/2', ...
   'Uff_lat/1', 'lat_uff_sum/1', 'lat_uff_sum/1', 'u_dev_lat_split/1');
sim_connect(mdl, 'u_dev_lat_split/1', 'surf_inc/1', 'u_dev_long_split/1', 'surf_inc/2', ...
   'u_dev_lat_split/2', 'surf_inc/3');
sim_connect(mdl, 'surf_inc/1', 'surf_sum/1', 'const_utrim/1', 'surf_sum/2', ...
   'surf_sum/1', 'G_gain/1', 'G_gain/1', 'alloc/1', 'G_gain/1', 'M_cmd/1');
sim_connect(mdl, 'u_dev_long_split/2', 'T_sum/1', 'const_Ttrim/1', 'T_sum/2', ...
   'T_sum/1', 'alloc/2', 'T_sum/1', 'T_cmd/1');
sim_connect(mdl, 'alloc/1', 'act_split/1', 'alloc/1', 'u_act/1');
sim_connect(mdl, 'act_split/1', 'u_mux/1', 'act_split/2', 'u_mux/2', ...
   'act_split/3', 'u_mux/3', 'act_split/4', 'u_mux/4', ...
   'act_split/5', 'u_mux/5', 'const_zero/1', 'u_mux/6');
sim_connect(mdl, 'u_mux/1', 'plant/1', 'wind_src/1', 'plant/2', ...
   'plant/1', 'x_state/1', 'plant/1', 'x_split/1', 'plant/1', 'meas/1');
sim_connect(mdl, 'u_dev_lat_split/1', 'u_dev_mux/1', 'u_dev_long_split/1', 'u_dev_mux/2', ...
   'u_dev_lat_split/2', 'u_dev_mux/3', 'u_dev_long_split/2', 'u_dev_mux/4', ...
   'u_dev_mux/1', 'u_dev/1');
sim_connect(mdl, 'long_int/1', 'xi_mux/1', 'lat_int/1', 'xi_mux/2', 'xi_mux/1', 'xi/1');

save_system(mdl, file);
info = struct('model', mdl, 'file', file);
info.census = sim_census(mdl);
info.opts = opts;
end
