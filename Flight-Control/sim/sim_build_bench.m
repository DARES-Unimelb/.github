   '6. 画布内那五条图如果不出线，双击兜底示波器看三段图。它设成不自动弹出。\n\n' ...
   '7. 满杆持续拉到底是一种故障注入：飞机应该收敛、侧滑有界、不掉高失控，而不是进螺旋。']));
sim_hmi('note', mdl, 'note_log', [2900 1000 4300 1340], sprintf([ ...
   '跑完的数据在哪，四路记录的通道是什么\n\n' ...
