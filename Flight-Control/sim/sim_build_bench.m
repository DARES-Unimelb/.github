   '控制器在 PID 与 LQR 之间切。两个控制器并联同跑，切换是瞬时的，不用重编译。' ...
   'LQR 通道里没有高度环，所以高度模式对它无效，做对比时两边都用姿态模式。\n\n' ...
   '仿真时长是工具栏 StopTime 框里的 sim_bench_t_end。要改就改 uacs_go.m 第 1.9 节' ...
   '的 uacs_sim.bench_run_s，跑一次再回来按 Run；也可以直接把那个框改成数字。']));
sim_hmi('note', mdl, 'note_watch', [840 2400 2000 2780], sprintf([ ...
   '看什么，什么算好\n\n' ...
