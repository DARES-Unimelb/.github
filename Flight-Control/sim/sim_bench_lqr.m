function info = sim_bench_lqr(mdl)
% SIM_BENCH_LQR 台架的 LQR 控制器子系统：整套线性二次型调节器装进一个块。
%
%   LQR控制器/   入 ref 5x1 / fb 9x1      出 du 4x1
%
%   du = [dda dde ddr dT]，与 PID 控制器同一接口，所以控制器选择只需一个 Switch。
%
% 结构与受验模型 model/uacs_lqr.slx 一致，纵向与横航两个通道各自独立、各自带积分增广
%   x_dev = x_abs - x_op                          偏差坐标
%   z     = integral(C_int*x_dev - r)             积分状态，输出限幅
%   u_dev = u_ff + K*([x_ref; 0] - [x_dev; z])    控制律
%
% 参考量从 ref 现算，而不是从预置场景读。ref 是绝对指令，LQR 的参考是偏差量，所以要
% 各自减掉配平工作点
%   dV_c     = V_c     - x_op_long(1)
%   dtheta_c = theta_c - x_op_long(4)
%   dphi_c   = phi_c   - x_op_lat(4)
%   dbeta_c  = 0       - x_op_lat(1)
% 工作点向量 sim_lqr_xop_long / sim_lqr_xop_lat 由 sim_push_design_vars 发布，就是
% design_lqr 用的那一个，所以这里减掉的量与增益的来源是同一个工作点。
%
% 参考映射用两个矩阵增益，这在线性上是精确的：lqr_reference 对这几个指令解的是线性
% 方程组，sim_lqr_refmap 已经把它与直接求解对拍过。
%
% 高度指令不在这里用。LQR 通道里没有高度环，所以高度模式对它无效；要在两种控制器
% 之间做公平对比，就都用姿态模式。

sub = [mdl '/LQR控制器'];
sim_add_block(mdl, 'LQR控制器', 'simulink/Ports & Subsystems/Subsystem', [1280 250 1450 450]);
sim_clear_model(sub);

sim_add_block(sub, 'ref', 'simulink/Sources/In1', sim_pos(0, 0, 30, 14), 'Port', '1');
sim_add_block(sub, 'fb', 'simulink/Sources/In1', sim_pos(0, 3, 30, 14), 'Port', '2');
sim_add_block(sub, 'ref_split', 'simulink/Signal Routing/Demux', sim_pos(1, 0, 40, 110), ...
   'Outputs', '5');
sim_add_block(sub, 'fb_split', 'simulink/Signal Routing/Demux', sim_pos(1, 3, 40, 200), ...
   'Outputs', '9');

% ---------------- 参考量 ----------------
sim_add_block(sub, 'xop_long', 'simulink/Sources/Constant', sim_pos(0, 9, 90, 30), ...
   'Value', 'sim_lqr_xop_long');
sim_add_block(sub, 'xop_long_split', 'simulink/Signal Routing/Demux', sim_pos(1, 9, 40, 90), ...
   'Outputs', '4');
sim_add_block(sub, 'xop_lat', 'simulink/Sources/Constant', sim_pos(0, 12, 90, 30), ...
   'Value', 'sim_lqr_xop_lat');
sim_add_block(sub, 'xop_lat_split', 'simulink/Signal Routing/Demux', sim_pos(1, 12, 40, 90), ...
   'Outputs', '4');
sim_add_block(sub, 'const_zero', 'simulink/Sources/Constant', sim_pos(0, 11, 60, 30), ...
   'Value', 'sim_c_zero');
sim_add_block(sub, 'long_cmd', 'simulink/Signal Routing/Mux', sim_pos(2, 9, 20, 40), ...
   'Inputs', '2');
sim_add_block(sub, 'long_cmd_op', 'simulink/Signal Routing/Mux', sim_pos(2, 10, 20, 40), ...
   'Inputs', '2');
sim_add_block(sub, 'long_ref', 'simulink/Math Operations/Sum', sim_pos(3, 9, 40, 40), ...
   'Inputs', '+-', 'IconShape', 'rectangular');
sim_add_block(sub, 'long_ref_split', 'simulink/Signal Routing/Demux', sim_pos(4, 9, 40, 50), ...
   'Outputs', '2');
sim_add_block(sub, 'lat_cmd', 'simulink/Signal Routing/Mux', sim_pos(2, 12, 20, 40), ...
   'Inputs', '2');
sim_add_block(sub, 'lat_cmd_op', 'simulink/Signal Routing/Mux', sim_pos(2, 13, 20, 40), ...
   'Inputs', '2');
sim_add_block(sub, 'lat_ref', 'simulink/Math Operations/Sum', sim_pos(3, 12, 40, 40), ...
   'Inputs', '+-', 'IconShape', 'rectangular');
sim_add_block(sub, 'lat_ref_split', 'simulink/Signal Routing/Demux', sim_pos(4, 12, 40, 50), ...
   'Outputs', '2');
sim_connect(sub, 'ref/1', 'ref_split/1', 'fb/1', 'fb_split/1');
sim_connect(sub, 'xop_long/1', 'xop_long_split/1', 'xop_lat/1', 'xop_lat_split/1');
sim_connect(sub, 'ref_split/4', 'long_cmd/1', 'ref_split/2', 'long_cmd/2', ...
   'xop_long_split/1', 'long_cmd_op/1', 'xop_long_split/4', 'long_cmd_op/2', ...
   'long_cmd/1', 'long_ref/1', 'long_cmd_op/1', 'long_ref/2', ...
   'long_ref/1', 'long_ref_split/1');
sim_connect(sub, 'const_zero/1', 'lat_cmd/1', 'ref_split/1', 'lat_cmd/2', ...
   'xop_lat_split/1', 'lat_cmd_op/1', 'xop_lat_split/4', 'lat_cmd_op/2', ...
   'lat_cmd/1', 'lat_ref/1', 'lat_cmd_op/1', 'lat_ref/2', ...
   'lat_ref/1', 'lat_ref_split/1');

% ---------------- 纵向通道 ----------------
sim_add_block(sub, 'Tref_long', 'simulink/Math Operations/Gain', sim_pos(5, 9, 90, 40), ...
   'Gain', 'sim_lqr_Tref_long', 'Multiplication', 'Matrix(K*u)');
sim_add_block(sub, 'Uff_long', 'simulink/Math Operations/Gain', sim_pos(5, 10, 90, 40), ...
   'Gain', 'sim_lqr_Uff_long', 'Multiplication', 'Matrix(K*u)');
sim_add_block(sub, 'long_abs', 'simulink/Signal Routing/Mux', sim_pos(2, 1, 20, 90), ...
   'Inputs', '4');
sim_add_block(sub, 'long_dev', 'simulink/Math Operations/Sum', sim_pos(3, 1, 40, 40), ...
   'Inputs', '+-', 'IconShape', 'rectangular');
sim_add_block(sub, 'C_long', 'simulink/Math Operations/Gain', sim_pos(4, 1, 70, 30), ...
   'Gain', 'sim_lqr_C_long', 'Multiplication', 'Matrix(K*u)');
sim_add_block(sub, 'long_int_err', 'simulink/Math Operations/Sum', sim_pos(5, 1, 40, 30), ...
   'Inputs', '+-', 'IconShape', 'rectangular');
sim_add_block(sub, 'long_int', 'simulink/Discrete/Discrete-Time Integrator', ...
   sim_pos(6, 1, 80, 40), 'gainval', 'sim_c_one', 'SampleTime', 'sim_ts_ctrl', ...
   'LimitOutput', 'on', 'UpperSaturationLimit', 'sim_lqr_zlim_long', ...
   'LowerSaturationLimit', 'sim_lqr_zlim_long_neg');
sim_add_block(sub, 'long_aug_dev', 'simulink/Signal Routing/Mux', sim_pos(7, 1, 20, 60), ...
   'Inputs', '2');
sim_add_block(sub, 'long_aug_ref', 'simulink/Signal Routing/Mux', sim_pos(7, 0, 20, 60), ...
   'Inputs', '2');
sim_add_block(sub, 'long_err', 'simulink/Math Operations/Sum', sim_pos(8, 0, 40, 40), ...
   'Inputs', '+-', 'IconShape', 'rectangular');
sim_add_block(sub, 'K_long', 'simulink/Math Operations/Gain', sim_pos(9, 0, 90, 40), ...
   'Gain', 'sim_lqr_K_long', 'Multiplication', 'Matrix(K*u)');
sim_add_block(sub, 'long_uff_sum', 'simulink/Math Operations/Sum', sim_pos(10, 0, 40, 40), ...
   'Inputs', '++', 'IconShape', 'rectangular');
sim_add_block(sub, 'u_long_split', 'simulink/Signal Routing/Demux', sim_pos(11, 0, 40, 50), ...
   'Outputs', '2');
sim_connect(sub, 'fb_split/6', 'long_abs/1', 'fb_split/8', 'long_abs/2', ...
   'fb_split/4', 'long_abs/3', 'fb_split/2', 'long_abs/4');
sim_connect(sub, 'long_abs/1', 'long_dev/1', 'xop_long/1', 'long_dev/2', ...
   'long_dev/1', 'C_long/1', 'long_dev/1', 'long_aug_dev/1');
sim_connect(sub, 'C_long/1', 'long_int_err/1', 'long_ref_split/1', 'long_int_err/2', ...
   'long_int_err/1', 'long_int/1', 'long_int/1', 'long_aug_dev/2');
sim_connect(sub, 'Tref_long/1', 'long_aug_ref/1', 'const_zero/1', 'long_aug_ref/2', ...
   'long_aug_ref/1', 'long_err/1', 'long_aug_dev/1', 'long_err/2', ...
   'long_err/1', 'K_long/1', 'K_long/1', 'long_uff_sum/2', ...
   'Uff_long/1', 'long_uff_sum/1', 'long_uff_sum/1', 'u_long_split/1', ...
   'long_ref/1', 'Tref_long/1', 'long_ref/1', 'Uff_long/1');

% ---------------- 横航通道 ----------------
sim_add_block(sub, 'Tref_lat', 'simulink/Math Operations/Gain', sim_pos(5, 12, 90, 40), ...
   'Gain', 'sim_lqr_Tref_lat', 'Multiplication', 'Matrix(K*u)');
sim_add_block(sub, 'Uff_lat', 'simulink/Math Operations/Gain', sim_pos(5, 13, 90, 40), ...
   'Gain', 'sim_lqr_Uff_lat', 'Multiplication', 'Matrix(K*u)');
sim_add_block(sub, 'lat_abs', 'simulink/Signal Routing/Mux', sim_pos(2, 4, 20, 90), ...
   'Inputs', '4');
sim_add_block(sub, 'lat_dev', 'simulink/Math Operations/Sum', sim_pos(3, 4, 40, 40), ...
   'Inputs', '+-', 'IconShape', 'rectangular');
sim_add_block(sub, 'C_lat', 'simulink/Math Operations/Gain', sim_pos(4, 4, 70, 30), ...
   'Gain', 'sim_lqr_C_lat', 'Multiplication', 'Matrix(K*u)');
sim_add_block(sub, 'lat_int_err', 'simulink/Math Operations/Sum', sim_pos(5, 4, 40, 30), ...
   'Inputs', '+-', 'IconShape', 'rectangular');
sim_add_block(sub, 'lat_int', 'simulink/Discrete/Discrete-Time Integrator', ...
   sim_pos(6, 4, 80, 40), 'gainval', 'sim_c_one', 'SampleTime', 'sim_ts_ctrl', ...
   'LimitOutput', 'on', 'UpperSaturationLimit', 'sim_lqr_zlim_lat', ...
   'LowerSaturationLimit', 'sim_lqr_zlim_lat_neg');
sim_add_block(sub, 'lat_aug_dev', 'simulink/Signal Routing/Mux', sim_pos(7, 4, 20, 60), ...
   'Inputs', '2');
sim_add_block(sub, 'lat_aug_ref', 'simulink/Signal Routing/Mux', sim_pos(7, 3, 20, 60), ...
   'Inputs', '2');
sim_add_block(sub, 'lat_err', 'simulink/Math Operations/Sum', sim_pos(8, 3, 40, 40), ...
   'Inputs', '+-', 'IconShape', 'rectangular');
sim_add_block(sub, 'K_lat', 'simulink/Math Operations/Gain', sim_pos(9, 3, 90, 40), ...
   'Gain', 'sim_lqr_K_lat', 'Multiplication', 'Matrix(K*u)');
sim_add_block(sub, 'lat_uff_sum', 'simulink/Math Operations/Sum', sim_pos(10, 3, 40, 40), ...
   'Inputs', '++', 'IconShape', 'rectangular');
sim_add_block(sub, 'u_lat_split', 'simulink/Signal Routing/Demux', sim_pos(11, 3, 40, 50), ...
   'Outputs', '2');
sim_connect(sub, 'fb_split/9', 'lat_abs/1', 'fb_split/3', 'lat_abs/2', ...
   'fb_split/5', 'lat_abs/3', 'fb_split/1', 'lat_abs/4');
sim_connect(sub, 'lat_abs/1', 'lat_dev/1', 'xop_lat/1', 'lat_dev/2', ...
   'lat_dev/1', 'C_lat/1', 'lat_dev/1', 'lat_aug_dev/1');
sim_connect(sub, 'C_lat/1', 'lat_int_err/1', 'lat_ref_split/2', 'lat_int_err/2', ...
   'lat_int_err/1', 'lat_int/1', 'lat_int/1', 'lat_aug_dev/2');
sim_connect(sub, 'Tref_lat/1', 'lat_aug_ref/1', 'const_zero/1', 'lat_aug_ref/2', ...
   'lat_aug_ref/1', 'lat_err/1', 'lat_aug_dev/1', 'lat_err/2', ...
   'lat_err/1', 'K_lat/1', 'K_lat/1', 'lat_uff_sum/2', ...
   'Uff_lat/1', 'lat_uff_sum/1', 'lat_uff_sum/1', 'u_lat_split/1', ...
   'lat_ref/1', 'Tref_lat/1', 'lat_ref/1', 'Uff_lat/1');

% ---------------- 输出 ----------------
% 横航的两路是 [dda ddr]，纵向的两路是 [dde dT]，拼成与 PID 同一顺序。
sim_add_block(sub, 'du_mux', 'simulink/Signal Routing/Mux', sim_pos(12, 1, 20, 90), ...
   'Inputs', '4');
sim_add_block(sub, 'du', 'simulink/Sinks/Out1', sim_pos(13, 1, 30, 14), 'Port', '1');
sim_connect(sub, 'u_lat_split/1', 'du_mux/1', 'u_long_split/1', 'du_mux/2', ...
   'u_lat_split/2', 'du_mux/3', 'u_long_split/2', 'du_mux/4', 'du_mux/1', 'du/1');
sim_name_line(sub, 'du_mux/1', 'du 4x1 [dda dde ddr dT]');

info = struct('name', 'LQR控制器', 'path', sub);
end
